import { writeFile } from 'node:fs/promises';

const target = process.argv[2] ?? 'preview';
if (!['preview', 'production'].includes(target)) {
  throw new Error('Target must be preview or production');
}

const base = target === 'production'
  ? 'https://pattaya-dinosaur-ticket-control.vercel.app'
  : 'https://pattaya-dinosaur-ticket-control-q6hxtsfgw-khant-min-htet2.vercel.app';

const config = `// Generated by scripts/configure-target.mjs. Do not edit by hand.
window.PDK_NATIVE_APP_CONFIG = Object.freeze({
  ownerUrl: '${base}/',
  staffUrl: '${base}/staff.html',
  environment: '${target}'
});
`;

await writeFile(new URL('../www/app-config.js', import.meta.url), config, 'utf8');
console.log(`Configured native app for ${target}: ${base}`);
